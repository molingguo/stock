export function localeFromPathname(pathname = '/') {
  const firstSegment = String(pathname).split('/').filter(Boolean)[0]?.toLowerCase();
  return firstSegment === 'zh-cn' || firstSegment === 'zh_cn' ? CHINESE_LOCALE : DEFAULT_LOCALE;
}

export function pathForLocale(locale, pathname = '/') {
  const segments = String(pathname).split('/').filter(Boolean);
  if (segments[0] && ['zh-cn', 'zh_cn'].includes(segments[0].toLowerCase())) segments.shift();
  const basePath = segments.length ? `/${segments.join('/')}` : '/';
  return locale === CHINESE_LOCALE
    ? `/zh-CN${basePath === '/' ? '/' : basePath}`
    : basePath;
}

export function createTranslator(locale) {
  const catalog = messages[locale] || messages[DEFAULT_LOCALE];
  return (key, values = {}) => {
    const template = catalog[key] ?? messages[DEFAULT_LOCALE][key] ?? key;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template
    );
  };
}

export function translateMarketTerm(value, locale) {
  return locale === CHINESE_LOCALE ? marketTermsZh[value] || value : value;
}

export function translateUniverseLabel(universe, fallback, locale) {
  const translator = createTranslator(locale);
  const key = `universe.${universe}Full`;
  const translated = translator(key);
  return translated === key ? fallback : translated;
}
